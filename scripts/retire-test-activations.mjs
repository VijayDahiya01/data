#!/usr/bin/env node
/**
 * Retire the activations left behind by automated runs, so the demo slot is
 * predictable again.
 *
 * Every `pnpm verify` and every portal e2e run approves campaigns, and each
 * approval leaves a live activation behind. They accumulate — dozens of them —
 * and because a Partner Agent ranks all eligible activations for a placement,
 * the demo site starts showing a different campaign on every refresh. Nothing
 * is broken; there is simply a crowd.
 *
 * Generated campaigns are recognised by the timestamp their names carry
 * (`Portal flow 1787…`, `Settlement 1787…`, `Phase 4 serving fixture 1787…`).
 * A campaign a person named — `remm`, `travel_insurance_offer 11` — has no such
 * digits and is left alone.
 *
 * Revoked, not deleted: §24 makes revocation the Partner's own unilateral act,
 * it is audited, and it is what an operator would actually do. Nothing is
 * removed from the database.
 *
 * Usage: node scripts/retire-test-activations.mjs [--dry-run]
 */
import { randomUUID } from 'node:crypto';

const API = process.env.API_URL ?? 'http://localhost:4000';
const KEYCLOAK =
  process.env.KEYCLOAK_TOKEN_URL ??
  'http://localhost:8081/realms/oolix/protocol/openid-connect/token';

const DRY_RUN = process.argv.includes('--dry-run');

/** Anything whose campaign name carries a 10-digit-or-longer timestamp. */
const GENERATED = /\d{10,}/;

/** Partner accounts that can revoke. A missing one is skipped, not fatal. */
const APPROVERS = ['partner.approver@example.test', 'rewards.approver@example.test'];

async function login(username) {
  try {
    const res = await fetch(KEYCLOAK, {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: new URLSearchParams({
        client_id: process.env.OIDC_CLIENT_ID ?? 'oolix-web',
        client_secret: process.env.OIDC_CLIENT_SECRET ?? 'local-only-secret',
        grant_type: 'password',
        username,
        password: process.env.SEED_PASSWORD ?? 'password',
      }),
    });
    const body = await res.json();
    return body.access_token ?? null;
  } catch {
    return null;
  }
}

async function apiCall(path, { method = 'GET', body, token } = {}) {
  const res = await fetch(`${API}${path}`, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/json',
      ...(body ? { 'Content-Type': 'application/json' } : {}),
      'Idempotency-Key': randomUUID(),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });
  const text = await res.text();
  let parsed = null;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = text;
  }
  return { status: res.status, body: parsed };
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

let retired = 0;
let kept = 0;
let failed = 0;

for (const username of APPROVERS) {
  const token = await login(username);
  if (!token) {
    console.log(`${username}: no such account — skipped`);
    continue;
  }

  const me = await apiCall('/v1/me/context', { token });
  const partner = me.body?.active_organization?.name ?? username;

  const queue = await apiCall('/v1/partner-requests?status=APPROVED', { token });
  const items = queue.body?.items ?? [];
  const stale = items.filter((r) => GENERATED.test(r.campaign_name ?? ''));
  kept += items.length - stale.length;

  console.log(`${partner}: ${items.length} approved, ${stale.length} generated by test runs`);
  if (DRY_RUN) continue;

  for (const request of stale) {
    // §41 rate-limits decisions. This is a bulk tidy-up rather than traffic, so
    // it paces itself and retries once rather than treating 429 as a failure.
    let res = await apiCall(`/v1/partner-requests/${request.request_id}/revoke`, {
      method: 'POST',
      token,
      body: { reason: 'Retiring an activation left behind by an automated test run.' },
    });
    if (res.status === 429) {
      await sleep(2500);
      res = await apiCall(`/v1/partner-requests/${request.request_id}/revoke`, {
        method: 'POST',
        token,
        body: { reason: 'Retiring an activation left behind by an automated test run.' },
      });
    }
    if (res.status < 400) retired += 1;
    else {
      failed += 1;
      if (failed <= 3) {
        console.log(
          `   ${res.status} on ${request.campaign_name}: ${JSON.stringify(res.body)?.slice(0, 120)}`,
        );
      }
    }
    await sleep(250);
  }
}

console.log(
  DRY_RUN
    ? `\nDry run: ${kept} named campaign(s) would be kept.`
    : `\nRetired ${retired}, kept ${kept} named campaign(s), ${failed} failed.` +
        (failed ? ' Re-run to finish the remainder.' : ''),
);
